export const GLYPH_W = 6; // 5 px 字寬＋1 px 字距

export function textWidth(s: string, scale = 1) {
  return s.length * GLYPH_W * scale - scale;
}

/** 畫一行字；沒有字形的字元以空白代替 */
export function drawText(bmp: Bitmap, s: string, x: number, y: number, color: string, scale = 1) {
  [...s.toUpperCase()].forEach((ch, i) => {
    const rows = (GLYPHS[ch] ?? GLYPHS[' ']).split(' ');
    rows.forEach((row, ry) => {
      [...row].forEach((bit, rx) => {
        if (bit === '#') bmp.rect(x + (i * GLYPH_W + rx) * scale, y + ry * scale, scale, scale, color);
      });
    });
  });
}
